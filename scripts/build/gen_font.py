#!/usr/bin/env python3
# Build kernel/src/font8x16.c from the authentic IBM VGA 8x16 ROM font
# (the typeface used by MS-DOS in VGA text mode). Source data: Linux kernel
# lib/fonts/font_8x16.c (cpi2fnt-generated from the IBM VGA ROM). The glyph
# bitmaps are functional bitmap data; layout/sizing of this table is ours.
import os, re

SRC = "/tmp/vga_linux.c"
DEST = "/home/z/my-project/kernel/src/font8x16.c"

raw = open(SRC).read()

# Extract every "0xNN" token that appears INSIDE the fontdata array body.
# The array body is between "fontdata_8x16 = {" ... the closing "};".
# Simpler: grab all 0xNN after the "{ 0, 0, FONTDATAMAX, 0 }, {" marker.
m = re.search(r"\{\s*0,\s*0,\s*FONTDATAMAX,\s*0\s*\},\s*\{(.*?)\};", raw, re.S)
if not m:
    raise SystemExit("could not locate fontdata array body")
body = m.group(1)
# Only count hex bytes that are followed by a comma (the bitmap data rows).
# The "/* N 0xNN 'c' */" comment lines have 0xNN WITHOUT a trailing comma.
bytes_hex = re.findall(r"0x([0-9A-Fa-f]{2})\s*,", body)
data = [int(h, 16) for h in bytes_hex]
if len(data) != 4096:
    raise SystemExit("expected 4096 bytes, got %d" % len(data))

# Each char = 16 bytes, char c at data[c*16 : c*16+16].
# Each byte = one row, bit7 (0x80) = leftmost pixel.

def render(ch):
    rows = data[ch*16:ch*16+16]
    out = []
    for b in rows:
        out.append("".join("#" if (b >> (7-i)) & 1 else "." for i in range(8)))
    return out

# sanity-check a few glyphs against the known IBM VGA shapes
print("=== sanity check (IBM VGA 8x16) ===")
for ch, name in [(0x41,'A'),(0x65,'e'),(0x53,'S'),(0x6f,'o'),(0x20,'space'),(0x40,'@')]:
    print("0x%02X '%s':" % (ch, chr(ch) if 0x20<=ch<0x7f else name))
    for r in render(ch):
        print("   " + r)

# emit the C table
out = []
out.append("/* ==========================================================================")
out.append(" *  Ziphu.OS 1.0  -  OpenZK  -  src/font8x16.c")
out.append(" *  Authentic IBM VGA 8x16 ROM font (the MS-DOS VGA text-mode typeface).")
out.append(" *  256 glyphs x 16 bytes; each byte = one row, bit7 = leftmost pixel.")
out.append(" *  Auto-generated by scripts/build/gen_font.py from the IBM VGA ROM data.")
out.append(" * ========================================================================== */")
out.append('#include "zk_types.h"')
out.append("const u8 zk_font8x16[256][16] = {")
for c in range(256):
    row = data[c*16:c*16+16]
    cells = ", ".join("0x%02X" % b for b in row)
    out.append("  { %s },  /* 0x%02X */" % (cells, c))
out.append("};")
text = "\n".join(out) + "\n"
with open(DEST, "w") as f:
    f.write(text)
print("wrote", DEST, os.path.getsize(DEST), "bytes")
